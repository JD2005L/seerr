it('creates and reconciles the fan-out table with PostgreSQL-compatible SQL', async (t) => {
  const original = datasource.options;
  Object.defineProperty(datasource, 'options', {
    value: { type: 'postgres' },
    configurable: true,
  });
  t.after(() =>
    Object.defineProperty(datasource, 'options', {
      value: original,
      configurable: true,
    })
  );
  const statements: string[] = [];
  t.mock.method(datasource, 'query', async (sql: string) => {
    statements.push(sql);
    return [];
  });
  await ensureFanoutTable();
  assert.match(statements[0], /generated by default as identity/i);
  assert.ok(
    statements.every((sql) => !/autoincrement|update or ignore/i.test(sql))
  );
  assert.ok(statements.some((sql) => /not exists/i.test(sql)));
});

it('binds PostgreSQL query placeholders in order without interpolating values', () => {
  assert.strictEqual(
    fanoutParameters('select ? where ? = ?', 'postgres'),
    'select $1 where $2 = $3'
  );
  assert.strictEqual(
    fanoutParameters('select ? where ? = ?', 'sqlite'),
    'select ? where ? = ?'
  );
});

it('reads PostgreSQL case-sensitive error fields and uses numbered parameters on status lookup', async (t) => {
  const original = datasource.options;
  Object.defineProperty(datasource, 'options', {
    value: { type: 'postgres' },
    configurable: true,
  });
  t.after(() =>
    Object.defineProperty(datasource, 'options', {
      value: original,
      configurable: true,
    })
  );
  const statements: string[] = [];
  t.mock.method(datasource, 'query', async (sql: string) => {
    statements.push(sql);
    if (/select id, owner, status/i.test(sql))
      return [
        {
          id: 1,
          owner: 'alice',
          status: 'remove_pending',
          ...(sql.includes('"lastError"')
            ? { lastError: 'failed' }
            : { lasterror: 'failed' }),
        },
      ];
    return [];
  });
  const result = await fanoutStatus(
    new User({ username: 'alice' }),
    undefined,
    MediaType.MOVIE,
    987655,
    null
  );
  assert.strictEqual(result.lastError, 'failed');
  assert.match(
    statements.find((sql) => /select id, owner, status/i.test(sql)) ?? '',
    /\$1.*\$2.*\$3/s
  );
});

